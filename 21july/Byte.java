class ByteExample1 {
    public static void main(String[] args) {

        byte daysInMonth = 31;
        System.out.println(daysInMonth);

        daysInMonth = 30;
        System.out.println(daysInMonth);

        daysInMonth = 28;
        System.out.println(daysInMonth);

        daysInMonth = 29;
        System.out.println(daysInMonth);
		
		byte workingDaysInWeek = 5;
        System.out.println(workingDaysInWeek);

        workingDaysInWeek = 6;
        System.out.println(workingDaysInWeek);
		
		byte marksInSubject = 95;
        System.out.println(marksInSubject);

        marksInSubject = 97;
        System.out.println(marksInSubject);
		
		byte chargePercentage = 88;
        System.out.println(chargePercentage);

        chargePercentage = 91;
        System.out.println(chargePercentage);
		
		byte eggsInTray = 30;
        System.out.println("Eggs before using: " + eggsInTray);

        eggsInTray = 24;
        System.out.println("Eggs after using: " + eggsInTray);
		
		 byte goalsInMatch = 2;
        System.out.println(goalsInMatch);

        goalsInMatch = 4;
        System.out.println(goalsInMatch);
		
		byte booksInBag = 6;
        System.out.println(booksInBag);

        booksInBag = 8;
        System.out.println(booksInBag);
		
		byte fansInRoom = 3;
        System.out.println(fansInRoom);

        fansInRoom = 4;
        System.out.println(fansInRoom);
		
		byte pensInBox = 20;
        System.out.println("Pens before selling: " + pensInBox);

        pensInBox = 12;
        System.out.println("Pens after selling: " + pensInBox);
		
		byte chairsInClass = 40;
        System.out.println("Chairs before adding: " + chairsInClass);

        chairsInClass = 45;
        System.out.println("Chairs after adding: " + chairsInClass);
    }
}

