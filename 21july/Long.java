class LongExample1 {
	public static void main(String[] args) {
		
		long worldPopulation = 8200000000L;
		System.out.println(worldPopulation);
		
		worldPopulation = 8300000000L;
		System.out.println(worldPopulation);
		
		long companyRevenue = 5000000000L;
		System.out.println("Revenue before growth: " + companyRevenue);
		
		companyRevenue = 6500000000L;
		System.out.println("Revenue after growth: " + companyRevenue);
		
		long mobileNumber = 9876543210L;
		System.out.println(mobileNumber);
		
		mobileNumber = 9123456789L;
		System.out.println(mobileNumber);
		
		long bankBalance = 125000000L;
		System.out.println(bankBalance);
		
		bankBalance = 150000000L;
		System.out.println(bankBalance);
		
		long distanceToSun = 149600000L;
		System.out.println(distanceToSun);
		
		distanceToSun = 150000000L;
		System.out.println(distanceToSun);
	
	}
}