class ShortExample1{
	public static void main(String[] args) {
		
		short salary = 25000;
		System.out.println(salary);
		
		salary = 30000;
		System.out.println(salary);
		
		short distanceInMeters = 1500;
		System.out.println(distanceInMeters);
		
		distanceInMeters = 2000;
		System.out.println(distanceInMeters);

		
		short studentsInSchool = 1200;
		System.out.println(studentsInSchool);
		
		studentsInSchool = 1350;
		System.out.println(studentsInSchool);
		
		short temperature = 32;
		System.out.println(temperature);
		
		temperature = 28;
		System.out.println(temperature);
		
		short housesInVillage = 850;
		System.out.println(housesInVillage);
		
		housesInVillage = 900;
		System.out.println(housesInVillage);
		
		short treesInPark = 1250;
		System.out.println(treesInPark);
		
		treesInPark = 1400;
		System.out.println(treesInPark);
		
		short audienceInHall = 600;
		System.out.println(audienceInHall);
		
		audienceInHall = 750;
		System.out.println(audienceInHall);
		
		short bagsInStore = 320;
		System.out.println("Bags before selling: " + bagsInStore);
		
		bagsInStore = 275;
		System.out.println("Bags after selling: " + bagsInStore);
		
		short bottlesInShop = 500;
		System.out.println("Bottles before purchase: " + bottlesInShop);
		
		bottlesInShop = 430;
		System.out.println("Bottles after purchase: " + bottlesInShop);
	}
}

