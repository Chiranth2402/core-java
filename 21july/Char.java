class CharExample1 {
	public static void main(String[] args) {
		
		char grade = 'A';
		System.out.println(grade);
		
		grade = 'B';
		System.out.println(grade);
		
		char gender = 'M';
		System.out.println(gender);
		
		gender = 'F';
		System.out.println(gender);
		
		char answer = 'Y';
		System.out.println(answer);
		
		answer = 'N';
		System.out.println(answer);
		
		char section = 'A';
		System.out.println(section);
		
		section = 'B';
		System.out.println(section);
		
		char firstLetter = 'J';
		System.out.println(firstLetter);
		
		firstLetter = 'K';
		System.out.println(firstLetter);
		
		char bloodGroup = 'O';
		System.out.println(bloodGroup);
		
		bloodGroup = 'A';
		System.out.println(bloodGroup);
		
		char direction = 'N';
		System.out.println(direction);
		
		direction = 'S';
		System.out.println(direction);
		
		char size = 'M';
		System.out.println(size);
		
		size = 'L';
		System.out.println(size);
		
		
		char currencySymbol = '$';
		System.out.println("Old Symbol: " + currencySymbol);
		
		currencySymbol = '₹';
		System.out.println("New Symbol: " + currencySymbol);
		
		
		char gradePoint = 'C';
		System.out.println("Previous Grade: " + gradePoint);
		
		gradePoint = 'A';
		System.out.println("Updated Grade: " + gradePoint);
		
		
	
	}
}



